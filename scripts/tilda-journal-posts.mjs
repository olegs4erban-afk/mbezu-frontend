await withSession(async ({ page }) => {
  await page.setViewportSize({ width: 1500, height: 1000 });
  await page.goto(`https://tilda.ru/identity/gofeeds/?projectid=${PROJECTID}`, { waitUntil: 'domcontentloaded', timeout: 60000 });
  await page.waitForTimeout(5000);
  await page.goto(`https://feeds.tilda.ru/posts/?feeduid=${FEEDUID}&projectid=${PROJECTID}`, { waitUntil: 'domcontentloaded', timeout: 60000 });
  await page.waitForTimeout(5000);
  console.log('на странице постов:', page.url());

  const payload = ARTICLES.map((a) => ({
    key: a.key, title: a.title, descr: a.descr, date: a.date, image: a.image,
    text: JSON.stringify(a.blocks),
  }));

  const out = await page.evaluate(async ({ posts, feeduid, projectid }) => {
    const call = async (params) => {
      const r = await fetch('/submit/', {
        method: 'POST', credentials: 'include',
        headers: { 'Content-Type': 'application/x-www-form-urlencoded; charset=UTF-8' },
        body: new URLSearchParams(params).toString(),
      });
      return r.json();
    };
    const res = { parts: null, created: [], errors: [] };
    const pl = await call({ action: 'parts_GetList', feeduid, projectid });
    const partsArr = (pl.data && (pl.data.parts || pl.data)) || [];
    const firstPart = Array.isArray(partsArr) && partsArr[0] ? (partsArr[0].uid || partsArr[0].partuid || '') : '';
    res.parts = { err: pl.error || 'ok', firstPart, count: Array.isArray(partsArr) ? partsArr.length : -1 };

    const list0 = await call({ action: 'posts_GetList', feeduid, projectid, items: 100 });
    const existing = Object.values((list0.data && list0.data.posts) || {});

    for (const p of posts) {
      try {
        let uid = null;
        const ex = existing.find((e) => (e.title || '') === p.title);
        if (ex) uid = ex.uid;
        if (!uid) {
          const add = await call({ action: 'posts_Add', feeduid, projectid, title: p.title, partuid: firstPart });
          if (add.error) { res.errors.push([p.key, 'add', add.error]); continue; }
          uid = add.data && add.data.uid;
        }
        const edit = await call({
          action: 'posts_Edit', feeduid, projectid, postuid: uid,
          title: p.title, descr: p.descr, date: p.date,
          image: p.image, mediadata: p.image, mediatype: 'image',
          text: p.text, parts: firstPart,
        });
        if (edit.error) res.errors.push([p.key, 'edit', edit.error]);
        const list1 = await call({ action: 'posts_GetList', feeduid, projectid, items: 100 });
        const row = Object.values((list1.data && list1.data.posts) || {}).find((e) => e.uid === uid);
        if (row && row.active !== 'y') {
          const act = await call({ action: 'posts_Active', feeduid, projectid, postuid: uid });
          if (act.error) res.errors.push([p.key, 'active', act.error]);
        }
        res.created.push({ key: p.key, uid, active0: row ? row.active : '?' });
        await new Promise((f) => setTimeout(f, 1200));
      } catch (e) { res.errors.push([p.key, 'exc', String(e).slice(0, 120)]); }
    }
    const fin = await call({ action: 'posts_GetList', feeduid, projectid, items: 100 });
    res.final = Object.values((fin.data && fin.data.posts) || {}).map((e) => ({ uid: e.uid, t: (e.title || '').slice(0, 44), active: e.active, parts: e.parts }));
    return res;
  }, { posts: payload, feeduid: FEEDUID, projectid: PROJECTID });

  console.log(JSON.stringify(out, null, 1));
  writeFileSync('.secrets/journal-feed.json', JSON.stringify({ feeduid: FEEDUID, ...out }, null, 1));
});
